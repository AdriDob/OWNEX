"""PR Builder — Creates pull requests with generated fixes."""

from __future__ import annotations

import asyncio
import os
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from core.autonomy.code_generator import CodeChange, GenerationPlan
from core.autonomy.repo_analyzer import RepoInfo


@dataclass
class PRResult:
    """Result of PR creation."""

    success: bool
    pr_url: str | None = None
    pr_number: int | None = None
    branch_name: str | None = None
    error: str | None = None
    data: dict[str, Any] | None = None


class PRBuilder:
    """Builds and submits pull requests with code changes."""

    def __init__(self, config: dict[str, Any] | None = None):
        self.config = config or {}
        self.github_token = os.environ.get("GITHUB_TOKEN") or self.config.get("github_token")
        self.gitlab_token = os.environ.get("GITLAB_TOKEN") or self.config.get("gitlab_token")
        self.default_branch = self.config.get("default_branch", "main")

    async def create_pr(
        self,
        plan: GenerationPlan,
        repo_info: RepoInfo,
        platform: str = "github",
    ) -> PRResult:
        """Create a pull request with the generated changes."""
        try:
            # 1. Create a new branch
            branch_name = self._generate_branch_name(plan.issue_analysis.issue_id)
            await self._create_branch(repo_info.path, branch_name, repo_info.default_branch)

            # 2. Apply all changes
            for change in plan.changes:
                await self._apply_change(repo_info.path, change)

            # 3. Apply test changes
            for change in plan.test_changes:
                await self._apply_change(repo_info.path, change)

            # 4. Commit changes
            commit_msg = self._generate_commit_message(plan)
            await self._commit_changes(repo_info.path, commit_msg)

            # 5. Push branch
            await self._push_branch(repo_info.path, branch_name, repo_info.git_remote)

            # 6. Create PR via platform API
            if platform == "github" or (repo_info.git_remote and "github.com" in repo_info.git_remote):
                return await self._create_github_pr(plan, repo_info, branch_name)
            elif platform == "gitlab" or (repo_info.git_remote and "gitlab.com" in repo_info.git_remote):
                return await self._create_gitlab_pr(plan, repo_info, branch_name)
            else:
                # Generic - just return branch info
                return PRResult(
                    success=True,
                    branch_name=branch_name,
                    data={"message": "Branch pushed. Create PR manually."},
                )

        except Exception as e:
            return PRResult(success=False, error=f"PR creation failed: {e}")

    def _generate_branch_name(self, issue_id: str) -> str:
        """Generate a unique branch name."""
        import time

        timestamp = int(time.time())
        return f"ownex/fix-{issue_id}-{timestamp}"

    async def _create_branch(self, repo_path: Path, branch_name: str, base_branch: str) -> None:
        """Create and checkout new branch from base."""
        # Fetch latest
        await self._run_git(repo_path, ["fetch", "origin", base_branch])

        # Create branch
        await self._run_git(repo_path, ["checkout", "-b", branch_name, f"origin/{base_branch}"])

    async def _apply_change(self, repo_path: Path, change: CodeChange) -> None:
        """Apply a single code change to the repository."""
        file_path = change.file_path
        if not file_path.is_absolute():
            file_path = repo_path / file_path

        # Ensure parent directory exists
        file_path.parent.mkdir(parents=True, exist_ok=True)

        # Write new content
        file_path.write_text(change.new_content, encoding="utf-8")

    def _generate_commit_message(self, plan: GenerationPlan) -> str:
        """Generate a descriptive commit message."""
        issue = plan.issue_analysis
        parts = [
            f"fix: {issue.title[:70]}" if issue.issue_type == "bug" else f"feat: {issue.title[:70]}",
            "",
            f"Issue: #{issue.issue_id} ({issue.platform})",
            f"Type: {issue.issue_type}",
            f"Severity: {issue.severity}",
        ]

        if issue.reproduction_steps:
            parts.extend(["", "Reproduction steps:", *[f"- {s}" for s in issue.reproduction_steps[:3]]])

        if plan.changes:
            parts.extend(["", "Changes:", *[f"- {c.file_path.name}: {c.description}" for c in plan.changes[:5]]])

        parts.extend(["", "Generated by OWNEX CoderAgent", f"Confidence: {plan.estimated_confidence:.0%}"])

        return "\n".join(parts)

    async def _commit_changes(self, repo_path: Path, message: str) -> None:
        """Stage and commit all changes."""
        await self._run_git(repo_path, ["add", "-A"])
        await self._run_git(repo_path, ["commit", "-m", message])

    async def _push_branch(self, repo_path: Path, branch_name: str, remote_url: str | None) -> None:
        """Push branch to remote."""
        remote = "origin"
        if remote_url and self.github_token:
            # Inject token into remote URL for push
            auth_url = remote_url.replace("https://", f"https://{self.github_token}@")
            await self._run_git(repo_path, ["remote", "set-url", remote, auth_url])

        await self._run_git(repo_path, ["push", "-u", remote, branch_name])

    async def _create_github_pr(
        self,
        plan: GenerationPlan,
        repo_info: RepoInfo,
        branch_name: str,
    ) -> PRResult:
        """Create PR via GitHub API."""
        if not self.github_token:
            return PRResult(
                success=False,
                error="GITHUB_TOKEN not configured",
                branch_name=branch_name,
            )

        # Extract owner/repo from git remote
        owner_repo = self._extract_github_owner_repo(repo_info.git_remote)
        if not owner_repo:
            return PRResult(
                success=False,
                error="Could not determine GitHub owner/repo",
                branch_name=branch_name,
            )

        owner, repo = owner_repo

        import aiohttp

        url = f"https://api.github.com/repos/{owner}/{repo}/pulls"
        headers = {
            "Authorization": f"Bearer {self.github_token}",
            "Accept": "application/vnd.github.v3+json",
        }

        body = self._generate_pr_body(plan)

        payload = {
            "title": f"[{plan.issue_analysis.platform.upper()}] {plan.issue_analysis.title[:80]}",
            "head": branch_name,
            "base": repo_info.default_branch,
            "body": body,
            "draft": plan.estimated_confidence < 0.7,
        }

        async with aiohttp.ClientSession() as session, session.post(url, headers=headers, json=payload) as resp:
            if resp.status == 201:
                data = await resp.json()
                return PRResult(
                    success=True,
                    pr_url=data["html_url"],
                    pr_number=data["number"],
                    branch_name=branch_name,
                    data=data,
                )
            else:
                error = await resp.text()
                return PRResult(
                    success=False,
                    error=f"GitHub API error {resp.status}: {error}",
                    branch_name=branch_name,
                )

    async def _create_gitlab_pr(
        self,
        plan: GenerationPlan,
        repo_info: RepoInfo,
        branch_name: str,
    ) -> PRResult:
        """Create MR via GitLab API."""
        if not self.gitlab_token:
            return PRResult(
                success=False,
                error="GITLAB_TOKEN not configured",
                branch_name=branch_name,
            )

        # Extract project path from git remote
        project_path = self._extract_gitlab_project(repo_info.git_remote)
        if not project_path:
            return PRResult(
                success=False,
                error="Could not determine GitLab project",
                branch_name=branch_name,
            )

        import aiohttp

        url = f"https://gitlab.com/api/v4/projects/{project_path}/merge_requests"
        headers = {"Authorization": f"Bearer {self.gitlab_token}"}

        payload = {
            "source_branch": branch_name,
            "target_branch": repo_info.default_branch,
            "title": f"[{plan.issue_analysis.platform.upper()}] {plan.issue_analysis.title[:80]}",
            "description": self._generate_pr_body(plan),
        }

        async with aiohttp.ClientSession() as session, session.post(url, headers=headers, json=payload) as resp:
            if resp.status == 201:
                data = await resp.json()
                return PRResult(
                    success=True,
                    pr_url=data["web_url"],
                    pr_number=data["iid"],
                    branch_name=branch_name,
                    data=data,
                )
            else:
                error = await resp.text()
                return PRResult(
                    success=False,
                    error=f"GitLab API error {resp.status}: {error}",
                    branch_name=branch_name,
                )

    def _extract_github_owner_repo(self, git_remote: str | None) -> tuple[str, str] | None:
        """Extract owner/repo from git remote URL."""
        if not git_remote:
            return None

        # https://github.com/owner/repo.git
        # git@github.com:owner/repo.git
        import re

        patterns = [
            r"github\.com[:/]([^/]+)/([^/.]+)",
        ]

        for pattern in patterns:
            match = re.search(pattern, git_remote)
            if match:
                return (match.group(1), match.group(2))

        return None

    def _extract_gitlab_project(self, git_remote: str | None) -> str | None:
        """Extract project path from GitLab remote."""
        if not git_remote:
            return None

        import re

        # gitlab.com/owner/repo.git or git@gitlab.com:owner/repo.git
        match = re.search(r"gitlab\.com[:/](.+?)(?:\.git)?$", git_remote)
        if match:
            return match.group(1).replace("/", "%2F")  # URL encode

        return None

    def _generate_pr_body(self, plan: GenerationPlan) -> str:
        """Generate PR description body."""
        issue = plan.issue_analysis

        sections = [
            f"## Fix for {issue.platform.upper()} Issue #{issue.issue_id}",
            "",
            f"**Original Issue:** [{issue.title}]({issue.url})",
            f"**Type:** {issue.issue_type} | **Severity:** {issue.severity} | **Confidence:** {plan.estimated_confidence:.0%}",
            "",
        ]

        if issue.reproduction_steps:
            sections.extend(
                ["### Reproduction Steps", *[f"{i + 1}. {s}" for i, s in enumerate(issue.reproduction_steps)], ""]
            )

        if issue.expected_behavior:
            sections.extend(["### Expected Behavior", issue.expected_behavior, ""])

        if issue.actual_behavior:
            sections.extend(["### Actual Behavior", issue.actual_behavior, ""])

        if issue.error_messages:
            sections.extend(["### Error Messages", *[f"```\n{e}\n```" for e in issue.error_messages[:3]], ""])

        sections.extend(
            [
                "### Changes Made",
                *[f"- `{c.file_path.name}`: {c.description}" for c in plan.changes],
                "",
                "### Tests Added/Updated",
                *[f"- `{c.file_path.name}`: {c.description}" for c in plan.test_changes],
                "",
                "---",
                f"*Generated by OWNEX CoderAgent (confidence: {plan.estimated_confidence:.0%})*",
            ]
        )

        return "\n".join(sections)

    async def _run_git(self, repo_path: Path, args: list[str]) -> str:
        """Run git command in repo."""
        proc = await asyncio.create_subprocess_exec(
            "git",
            *args,
            cwd=repo_path,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        stdout, stderr = await proc.communicate()

        if proc.returncode != 0:
            raise RuntimeError(f"git {' '.join(args)} failed: {stderr.decode()}")

        return stdout.decode().strip()


class PlatformPRBuilder:
    """Platform-specific PR builders for bounty platforms."""

    def __init__(self, config: dict[str, Any] | None = None):
        self.config = config or {}
        self.base_builder = PRBuilder(config)

    async def create_algora_pr(
        self,
        plan: GenerationPlan,
        repo_info: RepoInfo,
        bounty_id: str,
    ) -> PRResult:
        """Create PR for Algora bounty - uses Algora's submit_work mutation."""
        # First create standard PR
        pr_result = await self.base_builder.create_pr(plan, repo_info, "github")

        if not pr_result.success:
            return pr_result

        # Then submit to Algora via their API
        # This would call AlgoraExecutor.submit_pr
        return pr_result

    async def create_opire_pr(
        self,
        plan: GenerationPlan,
        repo_info: RepoInfo,
        bounty_id: str,
    ) -> PRResult:
        """Create PR for Opire bounty."""
        return await self.base_builder.create_pr(plan, repo_info, "github")

    async def create_issuehunt_pr(
        self,
        plan: GenerationPlan,
        repo_info: RepoInfo,
        issue_id: str,
    ) -> PRResult:
        """Create PR for IssueHunt."""
        return await self.base_builder.create_pr(plan, repo_info, "github")

    async def submit_freelancer_deliverable(
        self,
        plan: GenerationPlan,
        repo_info: RepoInfo,
        project_id: str,
    ) -> PRResult:
        """Submit deliverable for Freelancer project."""
        # For freelancer, we typically zip the repo and submit
        # This would call FreelancerExecutor.submit_deliverable
        pr_result = await self.base_builder.create_pr(plan, repo_info, "github")
        return pr_result


async def create_pr_from_plan(
    plan: GenerationPlan,
    repo_info: RepoInfo,
    platform: str = "github",
    config: dict[str, Any] | None = None,
) -> PRResult:
    """Convenience function to create PR from generation plan."""
    builder = PRBuilder(config)
    return await builder.create_pr(plan, repo_info, platform)
