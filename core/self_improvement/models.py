"""Data models for the OWNEX Self-Improvement Engine.

Core loop: Task -> Scaffold -> Rollout -> Evaluation -> Reward -> Experience.
All models are plain dataclasses with to_dict/from_dict so they can persist as
JSON and travel through the API layer without ORM coupling.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import UTC, datetime
from enum import StrEnum
from typing import Any


def utcnow_iso() -> str:
    return datetime.now(UTC).isoformat()


class TaskSource(StrEnum):
    """Where a task came from."""

    CURRICULUM = "curriculum"  # generated by the engine's task generator
    REFLECTION = "reflection"  # derived from a failure reflection
    CAREER_GAP = "career_gap"  # derived from the career engine's skill gaps
    CAPABILITY = "capability"  # targets a registered capability


class TaskCategory(StrEnum):
    """High-level category of a self-improvement task."""

    CODE = "code"  # write / fix / refactor code
    TEST = "test"  # write tests that must pass
    DEBUG = "debug"  # find and fix a bug
    DOCUMENTATION = "documentation"  # write docs explaining something
    ANALYSIS = "analysis"  # analyze a small input and produce a verdict
    GENERATION = "generation"  # produce structured output from a spec
    SECURITY = "security"  # find a vulnerability in a small sandbox
    REASONING = "reasoning"  # answer a question that requires reasoning


@dataclass
class Task:
    """A single unit of self-improvement work."""

    id: str
    title: str
    description: str
    category: TaskCategory
    difficulty: float  # 0.0 .. 1.0 (target success probability is 1 - difficulty-ish)
    skills: list[str] = field(default_factory=list)
    source: TaskSource = TaskSource.CURRICULUM
    capability: str = ""  # capability this task exercises ("" = generic)
    prompt: str = ""  # prompt handed to the solver
    expected: str = ""  # expected output / reference (for deterministic tasks)
    metadata: dict[str, Any] = field(default_factory=dict)
    created_at: str = field(default_factory=utcnow_iso)

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "title": self.title,
            "description": self.description,
            "category": self.category.value,
            "difficulty": self.difficulty,
            "skills": self.skills,
            "source": self.source.value,
            "capability": self.capability,
            "prompt": self.prompt,
            "expected": self.expected,
            "metadata": self.metadata,
            "created_at": self.created_at,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> Task:
        return cls(
            id=data["id"],
            title=data["title"],
            description=data["description"],
            category=TaskCategory(data["category"]),
            difficulty=float(data.get("difficulty", 0.5)),
            skills=list(data.get("skills", [])),
            source=TaskSource(data.get("source", "curriculum")),
            capability=data.get("capability", ""),
            prompt=data.get("prompt", ""),
            expected=data.get("expected", ""),
            metadata=data.get("metadata", {}),
            created_at=data.get("created_at", utcnow_iso()),
        )


@dataclass
class ScaffoldStep:
    """A step in a scaffold: instruction + how it will be verified."""

    index: int
    instruction: str
    verification: str  # human-readable check that will be run
    check_type: str = "file"  # file | command | assertion


@dataclass
class Scaffold:
    """Structured guidance produced for a task before solving."""

    task_id: str
    steps: list[ScaffoldStep] = field(default_factory=list)
    hints: list[str] = field(default_factory=list)
    generated_at: str = field(default_factory=utcnow_iso)

    def to_dict(self) -> dict[str, Any]:
        return {
            "task_id": self.task_id,
            "steps": [
                {
                    "index": s.index,
                    "instruction": s.instruction,
                    "verification": s.verification,
                    "check_type": s.check_type,
                }
                for s in self.steps
            ],
            "hints": self.hints,
            "generated_at": self.generated_at,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> Scaffold:
        return cls(
            task_id=data["task_id"],
            steps=[
                ScaffoldStep(
                    index=int(s["index"]),
                    instruction=s["instruction"],
                    verification=s["verification"],
                    check_type=s.get("check_type", "file"),
                )
                for s in data.get("steps", [])
            ],
            hints=list(data.get("hints", [])),
            generated_at=data.get("generated_at", utcnow_iso()),
        )


@dataclass
class Rollout:
    """A single attempt at solving a task inside the harness."""

    task_id: str
    attempt: int
    solution: str = ""  # code / text produced by the solver
    created_files: list[str] = field(default_factory=list)
    stdout: str = ""
    stderr: str = ""
    exit_code: int = -1
    error: str = ""  # harness-level error (policy violation, timeout, exception)
    duration_ms: int = 0
    started_at: str = field(default_factory=utcnow_iso)
    completed_at: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "task_id": self.task_id,
            "attempt": self.attempt,
            "solution": self.solution,
            "created_files": self.created_files,
            "stdout": self.stdout,
            "stderr": self.stderr,
            "exit_code": self.exit_code,
            "error": self.error,
            "duration_ms": self.duration_ms,
            "started_at": self.started_at,
            "completed_at": self.completed_at,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> Rollout:
        return cls(
            task_id=data["task_id"],
            attempt=int(data.get("attempt", 0)),
            solution=data.get("solution", ""),
            created_files=list(data.get("created_files", [])),
            stdout=data.get("stdout", ""),
            stderr=data.get("stderr", ""),
            exit_code=int(data.get("exit_code", -1)),
            error=data.get("error", ""),
            duration_ms=int(data.get("duration_ms", 0)),
            started_at=data.get("started_at", utcnow_iso()),
            completed_at=data.get("completed_at", ""),
        )


@dataclass
class Evaluation:
    """Objective evaluation of a rollout against the task expectation."""

    task_id: str
    rollout: Rollout
    valid: bool  # core validity (objective: ran + produced expected result)
    validity_score: float  # 0.0 .. 1.0
    checks_passed: int = 0
    checks_total: int = 0
    notes: list[str] = field(default_factory=list)

    @property
    def checks_summary(self) -> str:
        return f"{self.checks_passed}/{self.checks_total} checks passed"

    def to_dict(self) -> dict[str, Any]:
        return {
            "task_id": self.task_id,
            "rollout": self.rollout.to_dict(),
            "valid": self.valid,
            "validity_score": self.validity_score,
            "checks_passed": self.checks_passed,
            "checks_total": self.checks_total,
            "notes": self.notes,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> Evaluation:
        return cls(
            task_id=data["task_id"],
            rollout=Rollout.from_dict(data["rollout"]),
            valid=bool(data.get("valid", False)),
            validity_score=float(data.get("validity_score", 0.0)),
            checks_passed=int(data.get("checks_passed", 0)),
            checks_total=int(data.get("checks_total", 0)),
            notes=list(data.get("notes", [])),
        )


@dataclass
class Experience:
    """A completed loop iteration persisted for curriculum learning."""

    id: str
    task: Task
    scaffold: Scaffold
    evaluation: Evaluation
    reward: float  # R_task = Validity x Difficulty x Novelty
    difficulty_before: float
    difficulty_after: float
    created_at: str = field(default_factory=utcnow_iso)

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "task": self.task.to_dict(),
            "scaffold": self.scaffold.to_dict(),
            "evaluation": self.evaluation.to_dict(),
            "reward": self.reward,
            "difficulty_before": self.difficulty_before,
            "difficulty_after": self.difficulty_after,
            "created_at": self.created_at,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> Experience:
        return cls(
            id=data["id"],
            task=Task.from_dict(data["task"]),
            scaffold=Scaffold.from_dict(data["scaffold"]),
            evaluation=Evaluation.from_dict(data["evaluation"]),
            reward=float(data.get("reward", 0.0)),
            difficulty_before=float(data.get("difficulty_before", 0.5)),
            difficulty_after=float(data.get("difficulty_after", 0.5)),
            created_at=data.get("created_at", utcnow_iso()),
        )


@dataclass
class CapabilityStats:
    """Rolling performance statistics per capability / skill."""

    name: str
    attempts: int = 0
    successes: int = 0
    failures: int = 0
    avg_reward: float = 0.0
    best_reward: float = 0.0
    last_attempt_at: str = ""
    estimated_success_rate: float = 0.5  # smoothed, default neutral

    @property
    def success_rate(self) -> float:
        return self.successes / self.attempts if self.attempts else 0.0

    def to_dict(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "attempts": self.attempts,
            "successes": self.successes,
            "failures": self.failures,
            "avg_reward": self.avg_reward,
            "best_reward": self.best_reward,
            "last_attempt_at": self.last_attempt_at,
            "estimated_success_rate": self.estimated_success_rate,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> CapabilityStats:
        return cls(
            name=data["name"],
            attempts=int(data.get("attempts", 0)),
            successes=int(data.get("successes", 0)),
            failures=int(data.get("failures", 0)),
            avg_reward=float(data.get("avg_reward", 0.0)),
            best_reward=float(data.get("best_reward", 0.0)),
            last_attempt_at=data.get("last_attempt_at", ""),
            estimated_success_rate=float(data.get("estimated_success_rate", 0.5)),
        )


def make_task_id(prefix: str = "task") -> str:
    return f"{prefix}_{datetime.now(UTC).strftime('%Y%m%d%H%M%S%f')}"
