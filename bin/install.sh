#!/usr/bin/env bash
set -euo pipefail

# ═══════════════════════════════════════════════════════════════════════
# OWNEX OMEGA — INSTALL
# One-command setup for autonomous 30-day operation.
# ═══════════════════════════════════════════════════════════════════════

REPO="${REPO:-${1:-https://github.com/anomalyco/rastro.git}}"
INSTALL_DIR="${INSTALL_DIR:-${2:-$HOME/ownex}}"
OWNEX_ENV="$INSTALL_DIR/.venv"
OWNEX_CONFIG="$HOME/.config/ownex"
OWNEX_DATA="$HOME/.local/share/ownex"
OWNEX_LOG="$HOME/.local/state/ownex"

GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m'

info()  { echo -e "${BLUE}[INFO]${NC} $1"; }
ok()    { echo -e "${GREEN}[OK]${NC}   $1"; }
warn()  { echo -e "${YELLOW}[WARN]${NC} $1"; }
fail()  { echo -e "${RED}[FAIL]${NC} $1"; exit 1; }

echo ""
echo "  ╔══════════════════════════════════════════╗"
echo "  ║       OWNEX OMEGA — INSTALL v7.0.0       ║"
echo "  ║    Autonomous Self-Evolution Platform    ║"
echo "  ╚══════════════════════════════════════════╝"
echo ""

# ── 1. Prerequisites ────────────────────────────────────────────────
info "Checking prerequisites..."

command -v python3 >/dev/null 2>&1 || fail "Python 3 required"
command -v git >/dev/null 2>&1 || fail "Git required"
command -v node >/dev/null 2>&1 || warn "Node.js not found (frontend will not build)"
command -v npm >/dev/null 2>&1 || warn "npm not found (frontend will not build)"

PYTHON_VERSION=$(python3 --version 2>&1 | grep -oP '\d+\.\d+')
info "Python $PYTHON_VERSION found"
ok "Prerequisites satisfied"

# ── 2. Clone / Update ───────────────────────────────────────────────
if [ -d "$INSTALL_DIR" ]; then
    info "Updating existing installation at $INSTALL_DIR..."
    cd "$INSTALL_DIR" && git pull --ff-only 2>/dev/null || warn "Git pull failed, using existing code"
    ok "Updated"
else
    info "Cloning into $INSTALL_DIR..."
    git clone --depth 1 "$REPO" "$INSTALL_DIR" || fail "Clone failed"
    ok "Cloned"
fi

cd "$INSTALL_DIR"

# ── 3. Python virtualenv ────────────────────────────────────────────
if [ ! -d "$OWNEX_ENV" ]; then
    info "Creating Python virtual environment..."
    python3 -m venv "$OWNEX_ENV" || fail "Virtualenv creation failed"
    ok "Virtualenv created"
fi

info "Installing Python dependencies..."
source "$OWNEX_ENV/bin/activate"
pip install -q --upgrade pip setuptools wheel 2>/dev/null
pip install -q -r requirements.txt 2>/dev/null || pip install -q -e ".[dev]" 2>/dev/null || warn "Some dependencies may be missing"
pip install -q sentry-sdk loguru tenacity pip-audit vulture bandit safety 2>/dev/null || warn "Evolution tools not installed"
ok "Dependencies installed"

# ── 4. Configuration ────────────────────────────────────────────────
mkdir -p "$OWNEX_CONFIG" "$OWNEX_DATA" "$OWNEX_LOG"

if [ ! -f "$OWNEX_CONFIG/config.env" ]; then
    info "Creating default configuration..."
    cat > "$OWNEX_CONFIG/config.env" << 'CONFIGEOF'
# OWNEX OMEGA — Configuration
# Generated by install.sh

# Database
DATABASE_URL=sqlite:///$OWNEX_DATA/ownex.db

# Security
SECRET_KEY=$(python3 -c "import secrets; print(secrets.token_hex(32))")

# Providers
OMNIROUTE_API_KEY=
FCC_AUTH_TOKEN=orion-dev-local
OPENCODE_BASE_URL=

# Autonomy level (1=Detect, 2=Analyze, 3=Propose, 4=Prepare, 5=Validate, 6=Apply, 7=Learn)
AUTONOMY_LEVEL=3

# Self-evolution schedule (cron: daily at 03:00)
EVOLUTION_SCHEDULE="0 3 * * *"

# Monitoring
SENTRY_DSN=
CONFIGEOF
    chmod 600 "$OWNEX_CONFIG/config.env"
    ok "Configuration created at $OWNEX_CONFIG/config.env"
    warn "⚠ Edit $OWNEX_CONFIG/config.env and add your OMNIROUTE_API_KEY"
else
    ok "Configuration already exists"
fi

# ── 5. Systemd service ─────────────────────────────────────────────
SERVICE_NAME="ownex-omega"
SERVICE_PATH="$HOME/.config/systemd/user/$SERVICE_NAME.service"

if command -v systemctl >/dev/null 2>&1; then
    mkdir -p "$(dirname "$SERVICE_PATH")"
    if [ ! -f "$SERVICE_PATH" ]; then
        info "Creating systemd user service..."
        cat > "$SERVICE_PATH" << SERVICEEOF
[Unit]
Description=OWNEX OMEGA — Self-Evolution Platform
After=network.target

[Service]
Type=simple
WorkingDirectory=$INSTALL_DIR
EnvironmentFile=$OWNEX_CONFIG/config.env
ExecStart=$OWNEX_ENV/bin/uvicorn api.main:app --host 127.0.0.1 --port 8000 --reload
Restart=on-failure
RestartSec=10

[Install]
WantedBy=default.target
SERVICEEOF
        systemctl --user daemon-reload 2>/dev/null || true
        ok "Systemd service created"
        info "Run: systemctl --user enable --now $SERVICE_NAME"
    else
        ok "Systemd service already exists"
    fi
fi

# ── 6. Docker (optional) ────────────────────────────────────────────
if command -v docker >/dev/null 2>&1; then
    if [ -f "docker-compose.yml" ] || [ -f "compose.yml" ]; then
        info "Docker Compose file found. Run 'docker compose up -d' to start."
    fi
fi

# ── 7. Auto-start command ──────────────────────────────────────────
cat << 'SHELLEOF' > "$OWNEX_CONFIG/start.sh"
#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/../../.."
source .venv/bin/activate
export $(cat "$HOME/.config/ownex/config.env" | xargs)
exec uvicorn api.main:app --host 127.0.0.1 --port 8000
SHELLEOF
chmod +x "$OWNEX_CONFIG/start.sh"

# ── 8. Verify ───────────────────────────────────────────────────────
info "Verifying installation..."
source "$OWNEX_ENV/bin/activate"
python3 -c "
from core.evolution import (
    SelfEvolutionEngine, SelfHealer, InfrastructureAuditor,
    SelfTester, UpdateEngine, EvolutionSupervisor, AutonomyLevel,
)
print('Self Evolution Engine: OK')
from core.commander import build_context, get_audit_logger
print('Copilot Commander: OK')
from core.automation.workers import get_browser_workers
workers = get_browser_workers()
print(f'Workers: {list(workers.keys())}')
print('Installation verified successfully')
" 2>/dev/null && ok "Installation verified" || warn "Verification had warnings"

# ── 9. Summary ──────────────────────────────────────────────────────
echo ""
echo "  ╔══════════════════════════════════════════╗"
echo "  ║       INSTALLATION COMPLETE              ║"
echo "  ╚══════════════════════════════════════════╝"
echo ""
echo "  INSTALL_DIR:  $INSTALL_DIR"
echo "  CONFIG:       $OWNEX_CONFIG/config.env"
echo "  LOGS:         $OWNEX_LOG"
echo "  DATA:         $OWNEX_DATA"
echo ""
echo "  ── Quick start ──"
echo "  1. Edit config:  nano $OWNEX_CONFIG/config.env"
echo "  2. Start server: $OWNEX_CONFIG/start.sh"
echo "  3. Open browser: http://127.0.0.1:8000"
echo ""
echo "  ── Autonomous mode ──"
echo "  OWNEX starts at autonomy level 3 (Propose)."
echo "  It will detect issues, analyze them, and propose improvements."
echo "  No changes are applied without your approval."
echo ""
