def get_all_categories() -> list[Category]:
    """Get all categories."""
    return ALL_CATEGORIES


def get_categories_by_family(family: str) -> list[Category]:
    """Get categories filtered by family."""
    return [c for c in ALL_CATEGORIES if c.family == family]


def get_zero_barrier_categories() -> list[Category]:
    """Get categories with $0 barrier."""
    return [c for c in ALL_CATEGORIES if c.barrier == "$0"]


def get_high_ev_categories(min_ev: float = 30.0) -> list[Category]:
    """Get categories with EV/hour above threshold."""
    return [c for c in ALL_CATEGORIES if c.ev_per_hour >= min_ev]


def get_low_competition_categories() -> list[Category]:
    """Get categories with low competition."""
    return [c for c in ALL_CATEGORIES if c.competition == "low"]


def get_repeatable_categories() -> list[Category]:
    """Get categories that are repeatable."""
    return [c for c in ALL_CATEGORIES if c.repeatable]


def get_automation_friendly_categories(min_potential: float = 0.7) -> list[Category]:
    """Get categories with high automation potential."""
    return [c for c in ALL_CATEGORIES if c.automation_potential >= min_potential]


def get_category_stats() -> dict[str, Any]:
    """Get taxonomy statistics."""
    families = {}
    for c in ALL_CATEGORIES:
        families[c.family] = families.get(c.family, 0) + 1

    verified = sum(1 for c in ALL_CATEGORIES if c.verified)
    zero_barrier = sum(1 for c in ALL_CATEGORIES if c.barrier == "$0")
    low_competition = sum(1 for c in ALL_CATEGORIES if c.competition == "low")
    repeatable = sum(1 for c in ALL_CATEGORIES if c.repeatable)

    avg_ev = round(sum(c.ev_per_hour for c in ALL_CATEGORIES) / len(ALL_CATEGORIES), 1)
    avg_acceptance = round(sum(c.acceptance_probability for c in ALL_CATEGORIES) / len(ALL_CATEGORIES), 2)
    avg_automation = round(sum(c.automation_potential for c in ALL_CATEGORIES) / len(ALL_CATEGORIES), 2)

    return {
        "total": len(ALL_CATEGORIES),
        "verified": verified,
        "zero_barrier": zero_barrier,
        "low_competition": low_competition,
        "repeatable": repeatable,
        "by_family": families,
        "avg_ev_per_hour": avg_ev,
        "avg_acceptance_probability": avg_acceptance,
        "avg_automation_potential": avg_automation,
    }
