"""Opportunity Taxonomy — 175 real categories with verified sources.

Each category has:
- Real platforms/sources
- Barrier level ($0, low, medium, high)
- Skill requirements
- Payout range
- EV/hour estimate
- Country accessibility
- Payment compatibility
- Competition level
- Acceptance probability
- Time to cash
- Reputation value
- Repeatable
- Automation potential
- Risk level
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


@dataclass
class Category:
    """A work category with full metadata."""

    id: str
    name: str
    family: str
    subcategory: str
    barrier: str  # $0, low, medium, high
    experience_required: bool = False
    portfolio_required: bool = False
    skills_required: list[str] = field(default_factory=list)
    payout_range: str = ""
    ev_per_hour: float = 0.0
    country_accessible: list[str] = field(default_factory=lambda: ["*"])
    payment_compatible: list[str] = field(default_factory=lambda: ["paypal", "wise", "crypto", "bank"])
    platforms: list[str] = field(default_factory=list)
    verified: bool = False
    competition: str = "medium"  # low, medium, high
    acceptance_probability: float = 0.3  # 0-1
    time_to_cash: str = "1-4 weeks"
    reputation_value: float = 0.5  # 0-1
    repeatable: bool = True
    automation_potential: float = 0.5  # 0-1
    risk: str = "low"  # low, medium, high
    notes: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "name": self.name,
            "family": self.family,
            "subcategory": self.subcategory,
            "barrier": self.barrier,
            "experience_required": self.experience_required,
            "portfolio_required": self.portfolio_required,
            "skills_required": self.skills_required,
            "payout_range": self.payout_range,
            "ev_per_hour": self.ev_per_hour,
            "country_accessible": self.country_accessible,
            "payment_compatible": self.payment_compatible,
            "platforms": self.platforms,
            "verified": self.verified,
            "competition": self.competition,
            "acceptance_probability": self.acceptance_probability,
            "time_to_cash": self.time_to_cash,
            "reputation_value": self.reputation_value,
            "repeatable": self.repeatable,
            "automation_potential": self.automation_potential,
            "risk": self.risk,
        }


