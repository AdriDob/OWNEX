"""Finding Marketplace — Sell/transfer validated findings.

Enables hunters to list validated findings for sale/transfer to other hunters,
teams, or organizations. Handles escrow, verification, and transfer.
"""

from __future__ import annotations

import hashlib
import json
import logging
import os
from dataclasses import dataclass, field
from datetime import UTC, datetime
from enum import StrEnum
from pathlib import Path
from typing import Any

logger = logging.getLogger("ownex.marketplace.finding")


# ─── Listing Types ───


class ListingStatus(StrEnum):
    DRAFT = "draft"
    ACTIVE = "active"
    NEGOTIATING = "negotiating"
    IN_ESCROW = "in_escrow"
    COMPLETED = "completed"
    CANCELLED = "cancelled"
    EXPIRED = "expired"


class FindingType(StrEnum):
    VULNERABILITY = "vulnerability"
    EXPLOIT = "exploit"
    POC = "poc"
    RECON_DATA = "recon_data"
    METHODOLOGY = "methodology"
    TOOL_CONFIG = "tool_config"
    WORDLIST = "wordlist"
    SCAN_RESULTS = "scan_results"


class TransferType(StrEnum):
    FULL_TRANSFER = "full_transfer"  # Complete ownership transfer
    LICENSE = "license"  # License to use
    COLLABORATION = "collaboration"  # Joint work
    CONSULTING = "consulting"  # Advisory only


# ─── Data Models ───


@dataclass
class FindingListing:
    """A finding listed for sale/transfer."""

    # Required fields (no defaults)
    seller_id: str
    title: str
    finding_type: FindingType
    transfer_type: TransferType
    description: str
    severity: str  # critical, high, medium, low, info

    # Optional fields with defaults
    id: str = ""  # Generated by create_listing if empty
    platform: str | None = None  # HackerOne, Bugcrowd, etc.
    program: str | None = None
    reward_range: tuple[float, float] = (0.0, 0.0)  # min, max expected
    asking_price: float = 0.0
    currency: str = "USD"
    status: ListingStatus = ListingStatus.DRAFT
    tags: list[str] = field(default_factory=list)
    evidence_summary: str = ""  # Summary of evidence without full details
    poc_available: bool = False
    verified: bool = False
    verification_notes: str = ""
    created_at: str = field(default_factory=lambda: datetime.now(UTC).isoformat())
    updated_at: str = field(default_factory=lambda: datetime.now(UTC).isoformat())
    expires_at: str | None = None
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class FindingOffer:
    """An offer on a finding listing."""

    # Required fields
    listing_id: str
    buyer_id: str
    offered_price: float

    # Optional fields with defaults
    id: str = ""  # Generated by create_offer if empty
    currency: str = "USD"
    transfer_type: TransferType = TransferType.FULL_TRANSFER
    message: str = ""
    status: str = "pending"  # pending, accepted, rejected, countered, withdrawn
    counter_price: float | None = None
    created_at: str = field(default_factory=lambda: datetime.now(UTC).isoformat())
    updated_at: str = field(default_factory=lambda: datetime.now(UTC).isoformat())
    expires_at: str | None = None
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class FindingTransaction:
    """A completed finding transaction."""

    # Required fields
    listing_id: str
    offer_id: str
    seller_id: str
    buyer_id: str
    final_price: float
    transfer_type: TransferType

    # Optional fields with defaults
    id: str = ""  # Generated by complete_transaction if empty
    currency: str = "USD"
    escrow_id: str | None = None
    status: str = "completed"  # completed, disputed, refunded
    completed_at: str = field(default_factory=lambda: datetime.now(UTC).isoformat())
    delivery_confirmed: bool = False
    delivery_confirmed_at: str | None = None
    dispute_reason: str | None = None
    metadata: dict[str, Any] = field(default_factory=dict)


# ─── Marketplace Engine ───


class FindingMarketplace:
    """Manages finding listings, offers, and transactions."""

    def __init__(self, data_dir: str | Path | None = None) -> None:
        base = os.environ.get("OWNEX_DATA_DIR")
        self.data_dir = (
            Path(data_dir)
            if data_dir
            else (Path(base) if base else Path(__file__).resolve().parents[3] / "data" / "marketplace")
        )
        self.data_dir.mkdir(parents=True, exist_ok=True)
        self.listings_file = self.data_dir / "listings.json"
        self.offers_file = self.data_dir / "offers.json"
        self.transactions_file = self.data_dir / "transactions.json"
        self.reputation_file = self.data_dir / "reputation.json"

    # ─── Listing Management ───

    def create_listing(self, listing: FindingListing) -> FindingListing:
        listing.id = (
            listing.id
            or f"listing_{hashlib.sha256(f'{listing.seller_id}{listing.title}{datetime.now(UTC)}'.encode()).hexdigest()[:12]}"
        )
        listing.created_at = datetime.now(UTC).isoformat()
        listing.updated_at = listing.created_at
        listings = self._load_listings()
        listings[listing.id] = listing.__dict__
        self._save_listings(listings)
        logger.info(f"Created listing {listing.id} by {listing.seller_id}")
        return listing

    def get_listing(self, listing_id: str) -> FindingListing | None:
        listings = self._load_listings()
        if listing_id in listings:
            return FindingListing(**listings[listing_id])
        return None

    def update_listing(self, listing_id: str, seller_id: str, updates: dict[str, Any]) -> FindingListing | None:
        listings = self._load_listings()
        if listing_id not in listings:
            return None
        listing = listings[listing_id]
        if listing["seller_id"] != seller_id:
            raise PermissionError("Only seller can update listing")
        for k, v in updates.items():
            if k in ("id", "seller_id", "created_at"):
                continue
            listing[k] = v
        listing["updated_at"] = datetime.now(UTC).isoformat()
        self._save_listings(listings)
        return FindingListing(**listing)

    def publish_listing(self, listing_id: str, seller_id: str) -> FindingListing | None:
        return self.update_listing(listing_id, seller_id, {"status": ListingStatus.ACTIVE})

    def get_listings(
        self,
        seller_id: str | None = None,
        status: ListingStatus | None = None,
        finding_type: FindingType | None = None,
        min_price: float | None = None,
        max_price: float | None = None,
        limit: int = 50,
    ) -> list[FindingListing]:
        listings = self._load_listings()
        result = []
        for listing_data in listings.values():
            if seller_id and listing_data["seller_id"] != seller_id:
                continue
            if status and listing_data["status"] != status.value:
                continue
            if finding_type and listing_data["finding_type"] != finding_type.value:
                continue
            if min_price is not None and listing_data["asking_price"] < min_price:
                continue
            if max_price is not None and listing_data["asking_price"] > max_price:
                continue
            result.append(FindingListing(**listing_data))
        result.sort(key=lambda x: x.created_at, reverse=True)
        return result[:limit]

    # ─── Offers ───

    def create_offer(self, offer: FindingOffer) -> FindingOffer:
        offer.id = (
            offer.id
            or f"offer_{hashlib.sha256(f'{offer.listing_id}{offer.buyer_id}{datetime.now(UTC)}'.encode()).hexdigest()[:12]}"
        )
        offer.created_at = datetime.now(UTC).isoformat()
        offer.updated_at = offer.created_at
        from datetime import timedelta as _td

        offer.expires_at = (datetime.now(UTC) + _td(days=7)).isoformat()

        # Verify listing exists and is active
        listing = self.get_listing(offer.listing_id)
        if not listing:
            raise ValueError("Listing not found")
        if listing.status != ListingStatus.ACTIVE:
            raise ValueError("Listing not active")
        if listing.seller_id == offer.buyer_id:
            raise ValueError("Cannot make offer on own listing")

        offers = self._load_offers()
        offers[offer.id] = offer.__dict__
        self._save_offers(offers)
        logger.info(f"Created offer {offer.id} on listing {offer.listing_id} by {offer.buyer_id}")
        return offer

    def get_offer(self, offer_id: str) -> FindingOffer | None:
        offers = self._load_offers()
        if offer_id in offers:
            return FindingOffer(**offers[offer_id])
        return None

    def get_offers_for_listing(self, listing_id: str) -> list[FindingOffer]:
        offers = self._load_offers()
        return [FindingOffer(**o) for o in offers.values() if o["listing_id"] == listing_id]

    def update_offer(self, offer_id: str, buyer_id: str, updates: dict[str, Any]) -> FindingOffer | None:
        offers = self._load_offers()
        if offer_id not in offers:
            return None
        offer = offers[offer_id]
        if offer["buyer_id"] != buyer_id:
            raise PermissionError("Only buyer can update offer")
        for k, v in updates.items():
            if k in ("id", "listing_id", "buyer_id", "created_at"):
                continue
            offer[k] = v
        offer["updated_at"] = datetime.now(UTC).isoformat()
        self._save_offers(offers)
        return FindingOffer(**offer)

    def accept_offer(self, offer_id: str, seller_id: str) -> FindingOffer | None:
        offers = self._load_offers()
        if offer_id not in offers:
            return None
        offer = offers[offer_id]
        listing = self.get_listing(offer["listing_id"])
        if not listing or listing.seller_id != seller_id:
            raise PermissionError("Only seller can accept offer")

        offer["status"] = "accepted"
        offer["updated_at"] = datetime.now(UTC).isoformat()
        self._save_offers(offers)

        # Mark listing as negotiating
        self.update_listing(offer["listing_id"], seller_id, {"status": ListingStatus.NEGOTIATING})

        return FindingOffer(**offer)

    def reject_offer(self, offer_id: str, seller_id: str) -> FindingOffer | None:
        offers = self._load_offers()
        if offer_id not in offers:
            return None
        offer = offers[offer_id]
        listing = self.get_listing(offer["listing_id"])
        if not listing or listing.seller_id != seller_id:
            raise PermissionError("Only seller can reject offer")
        offer["status"] = "rejected"
        offer["updated_at"] = datetime.now(UTC).isoformat()
        self._save_offers(offers)
        return FindingOffer(**offer)

    def counter_offer(self, offer_id: str, seller_id: str, counter_price: float) -> FindingOffer | None:
        offers = self._load_offers()
        if offer_id not in offers:
            return None
        offer = offers[offer_id]
        listing = self.get_listing(offer["listing_id"])
        if not listing or listing.seller_id != seller_id:
            raise PermissionError("Only seller can counter offer")
        offer["status"] = "countered"
        offer["counter_price"] = counter_price
        offer["updated_at"] = datetime.now(UTC).isoformat()
        self._save_offers(offers)
        return FindingOffer(**offer)

    # ─── Transactions ───

    def complete_transaction(
        self,
        listing_id: str,
        offer_id: str,
        seller_id: str,
        buyer_id: str,
        final_price: float,
        escrow_id: str | None = None,
    ) -> FindingTransaction:
        listing = self.get_listing(listing_id)
        if not listing:
            raise ValueError("Listing not found")
        if listing.seller_id != seller_id:
            raise PermissionError("Only seller can complete transaction")

        offer = self.get_offer(offer_id)
        if not offer or offer.buyer_id != buyer_id:
            raise ValueError("Invalid offer")

        if offer.status != "accepted":
            raise ValueError("Offer not accepted")

        transaction = FindingTransaction(
            id=f"txn_{hashlib.sha256(f'{listing_id}{offer_id}{datetime.now(UTC)}'.encode()).hexdigest()[:12]}",
            listing_id=listing_id,
            offer_id=offer_id,
            seller_id=seller_id,
            buyer_id=buyer_id,
            final_price=offer.counter_price or offer.offered_price,
            currency=offer.currency,
            transfer_type=offer.transfer_type,
            escrow_id=escrow_id,
        )

        # Update listing
        self.update_listing(listing_id, seller_id, {"status": ListingStatus.COMPLETED})

        # Update offer
        offers = self._load_offers()
        offers[offer_id]["status"] = "completed"
        offers[offer_id]["updated_at"] = datetime.now(UTC).isoformat()
        self._save_offers(offers)

        # Record transaction
        transactions = self._load_transactions()
        transactions[transaction.id] = transaction.__dict__
        self._save_transactions(transactions)

        # Update reputation
        self._update_reputation(seller_id, True)
        self._update_reputation(buyer_id, True)

        logger.info(f"Completed transaction {transaction.id}: {listing_id} sold for ${final_price}")
        return transaction

    def confirm_delivery(self, transaction_id: str, buyer_id: str) -> FindingTransaction | None:
        transactions = self._load_transactions()
        if transaction_id not in transactions:
            return None
        txn = transactions[transaction_id]
        if txn["buyer_id"] != buyer_id:
            raise PermissionError("Only buyer can confirm delivery")
        txn["delivery_confirmed"] = True
        txn["delivery_confirmed_at"] = datetime.now(UTC).isoformat()
        self._save_transactions(transactions)
        return FindingTransaction(**txn)

    # ─── Reputation ───

    def _update_reputation(self, user_id: str, success: bool) -> None:
        rep = self._load_reputation()
        if user_id not in rep:
            rep[user_id] = {"sales": 0, "purchases": 0, "successful": 0, "disputes": 0, "rating": 5.0}
        if success:
            rep[user_id]["successful"] += 1
        else:
            rep[user_id]["disputes"] += 1
        total = rep[user_id]["sales"] + rep[user_id]["purchases"]
        if total > 0:
            rep[user_id]["rating"] = round(rep[user_id]["successful"] / total * 5.0, 1)
        self._save_reputation(rep)

    def get_reputation(self, user_id: str) -> dict[str, Any]:
        rep = self._load_reputation()
        return rep.get(user_id, {"sales": 0, "purchases": 0, "successful": 0, "disputes": 0, "rating": 5.0})

    # ─── Search & Discovery ───

    def search_listings(
        self,
        query: str,
        finding_type: FindingType | None = None,
        min_price: float | None = None,
        max_price: float | None = None,
        severity: str | None = None,
        limit: int = 20,
    ) -> list[FindingListing]:
        listings = self.get_listings(status=ListingStatus.ACTIVE, limit=1000)
        query_lower = query.lower()
        results = []
        for listing in listings:
            if query_lower not in listing.title.lower() and query_lower not in listing.description.lower():
                continue
            if finding_type and listing.finding_type != finding_type:
                continue
            if severity and listing.severity != severity:
                continue
            results.append(listing)
        return results[:limit]

    # ─── Persistence ───

    def _load_listings(self) -> dict[str, dict]:
        try:
            with open(self.listings_file, encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            return {}

    def _save_listings(self, listings: dict[str, dict]) -> None:
        with open(self.listings_file, "w", encoding="utf-8") as f:
            json.dump(listings, f, indent=2, ensure_ascii=False, default=str)

    def _load_offers(self) -> dict[str, dict]:
        try:
            with open(self.offers_file, encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            return {}

    def _save_offers(self, offers: dict[str, dict]) -> None:
        with open(self.offers_file, "w", encoding="utf-8") as f:
            json.dump(offers, f, indent=2, ensure_ascii=False, default=str)

    def _load_transactions(self) -> dict[str, dict]:
        try:
            with open(self.transactions_file, encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            return {}

    def _save_transactions(self, transactions: dict[str, dict]) -> None:
        with open(self.transactions_file, "w", encoding="utf-8") as f:
            json.dump(transactions, f, indent=2, ensure_ascii=False, default=str)

    def _load_reputation(self) -> dict[str, dict]:
        try:
            with open(self.reputation_file, encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            return {}

    def _save_reputation(self, rep: dict[str, dict]) -> None:
        with open(self.reputation_file, "w", encoding="utf-8") as f:
            json.dump(rep, f, indent=2, ensure_ascii=False, default=str)


# ─── Global Instance ───

_finding_marketplace: FindingMarketplace | None = None


def get_finding_marketplace() -> FindingMarketplace:
    global _finding_marketplace
    if _finding_marketplace is None:
        _finding_marketplace = FindingMarketplace()
    return _finding_marketplace


# ─── API Functions ───


def create_listing(
    seller_id: str,
    title: str,
    finding_type: FindingType,
    transfer_type: TransferType,
    description: str,
    severity: str,
    asking_price: float,
    platform: str | None = None,
    program: str | None = None,
    tags: list[str] | None = None,
) -> FindingListing:
    marketplace = get_finding_marketplace()
    listing = FindingListing(
        seller_id=seller_id,
        title=title,
        finding_type=finding_type,
        transfer_type=transfer_type,
        description=description,
        severity=severity,
        platform=platform,
        program=program,
        asking_price=asking_price,
        tags=tags or [],
    )
    return marketplace.create_listing(listing)


def get_listing(listing_id: str) -> FindingListing | None:
    return get_finding_marketplace().get_listing(listing_id)


def list_listings(
    seller_id: str | None = None,
    status: ListingStatus | None = None,
    finding_type: FindingType | None = None,
    min_price: float | None = None,
    max_price: float | None = None,
    limit: int = 50,
) -> list[FindingListing]:
    return get_finding_marketplace().get_listings(seller_id, status, finding_type, min_price, max_price, limit)


def make_offer(
    listing_id: str,
    buyer_id: str,
    offered_price: float,
    transfer_type: TransferType = TransferType.FULL_TRANSFER,
    message: str = "",
) -> FindingOffer:
    marketplace = get_finding_marketplace()
    offer = FindingOffer(
        listing_id=listing_id,
        buyer_id=buyer_id,
        offered_price=offered_price,
        transfer_type=transfer_type,
        message=message,
    )
    return marketplace.create_offer(offer)


def accept_offer(offer_id: str, seller_id: str) -> FindingOffer | None:
    return get_finding_marketplace().accept_offer(offer_id, seller_id)


def reject_offer(offer_id: str, seller_id: str) -> FindingOffer | None:
    return get_finding_marketplace().reject_offer(offer_id, seller_id)


def counter_offer(offer_id: str, seller_id: str, counter_price: float) -> FindingOffer | None:
    return get_finding_marketplace().counter_offer(offer_id, seller_id, counter_price)


def complete_transaction(
    listing_id: str,
    offer_id: str,
    seller_id: str,
    buyer_id: str,
    final_price: float,
    escrow_id: str | None = None,
) -> FindingTransaction:
    return get_finding_marketplace().complete_transaction(
        listing_id, offer_id, seller_id, buyer_id, final_price, escrow_id
    )


def get_user_reputation(user_id: str) -> dict[str, Any]:
    return get_finding_marketplace().get_reputation(user_id)


def search_findings(
    query: str,
    finding_type: FindingType | None = None,
    min_price: float | None = None,
    max_price: float | None = None,
    severity: str | None = None,
    limit: int = 20,
) -> list[FindingListing]:
    return get_finding_marketplace().search_listings(query, finding_type, min_price, max_price, severity, limit)
