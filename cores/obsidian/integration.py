"""Obsidian Integration for OWNEX OMEGA.

Sistema de integración con Obsidian para:
- Notas diarias automáticas
- Planificación diaria
- Registro de progreso
- Integración con MERLIN
"""

from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path
from typing import Any, Optional

from cores.setup.steps.enhanced_personalization import get_enhanced_personalization_system


class ObsidianIntegration:
    """Integración con Obsidian."""

    def __init__(self, vault_path: Optional[Path] = None):
        self.system = get_enhanced_personalization_system()
        self.vault_path = vault_path or Path(self.system.profile.obsidian_vault_path)
        self.daily_notes_path = self.vault_path / "Daily Notes"
        self.templates_path = self.vault_path / "Templates"
        self.merlin_notes_path = self.vault_path / "MERLIN"

    def initialize_vault(self) -> dict[str, Any]:
        """Inicializar estructura del vault de Obsidian."""
        if not self.vault_path.exists():
            return {
                "success": False,
                "error": "Vault path does not exist",
            }

        # Crear directorios necesarios
        self.daily_notes_path.mkdir(exist_ok=True)
        self.templates_path.mkdir(exist_ok=True)
        self.merlin_notes_path.mkdir(exist_ok=True)

        # Crear template de nota diaria
        self._create_daily_note_template()

        # Crear template de planificación
        self._create_planning_template()

        # Crear archivo de configuración de MERLIN
        self._create_merlin_config()

        return {
            "success": True,
            "message": "Vault initialized successfully",
            "paths": {
                "daily_notes": str(self.daily_notes_path),
                "templates": str(self.templates_path),
                "merlin": str(self.merlin_notes_path),
            },
        }

    def _create_daily_note_template(self) -> None:
        """Crear template de nota diaria."""
        template_path = self.templates_path / "Daily Note.md"
        name = self.system.profile.preferred_name or self.system.profile.name

        template = f"""---
created: {{{{date}}}}
tags: [daily, plan]
type: daily-note
---

# {{{{date}}}}

## 🧙 MERLIN Daily Plan for {name}

### 🎯 Objetivo del Día
{{{{daily_goal}}}}

### ✅ Tareas Prioritarias
- [ ] Tarea 1
- [ ] Tarea 2
- [ ] Tarea 3

### 📊 Progreso
- [ ] Progreso 1
- [ ] Progreso 2

### 💡 Notas
- Nota 1
- Nota 2

### 🏆 Logros del Día
- Logro 1
- Logro 2

### 📝 Reflexión
{{{{reflection}}}}

---
*Generated by MERLIN - OWNEX OMEGA*
"""

        template_path.write_text(template, encoding="utf-8")

    def _create_planning_template(self) -> None:
        """Crear template de planificación."""
        template_path = self.templates_path / "Planning.md"

        template = """---
tags: [planning]
type: planning
---

# Planificación

## Objetivos Semanales
- [ ] Objetivo 1
- [ ] Objetivo 2
- [ ] Objetivo 3

## Objetivos Mensuales
- [ ] Objetivo 1
- [ ] Objetivo 2
- [ ] Objetivo 3

## Proyectos
- [ ] Proyecto 1
- [ ] Proyecto 2

## Ideas
- Idea 1
- Idea 2

---
*Generated by MERLIN - OWNEX OMEGA*
"""

        template_path.write_text(template, encoding="utf-8")

    def _create_merlin_config(self) -> None:
        """Crear archivo de configuración de MERLIN."""
        config_path = self.merlin_notes_path / "MERLIN Config.md"

        config = f"""---
tags: [config, merlin]
type: config
---

# MERLIN Configuration

## Usuario
- Nombre: {self.system.profile.name}
- Nombre preferido: {self.system.profile.preferred_name}
- Nivel de experiencia: {self.system.profile.experience_level.value}
- Modo de trabajo: {self.system.profile.work_mode.value}
- Nivel de guía: {self.system.profile.guidance_level.value}

## Objetivos
- Objetivo principal: {self.system.profile.primary_goal}
- Meta mensual: ${self.system.profile.income_target_monthly:.0f}

## Configuración
- Horas de trabajo: {self.system.profile.work_hours_start} - {self.system.profile.work_hours_end}
- Días de trabajo: {', '.join(self.system.profile.work_days)}
- Voice enabled: {self.system.profile.voice_enabled}
- Obsidian daily notes: {self.system.profile.obsidian_daily_notes}

## Integraciones
- Obsidian vault: {self.system.profile.obsidian_vault_path}
- Calendar: {self.system.profile.calendar_integration}
- Email: {self.system.profile.email_integration}

---
*Generated by MERLIN - OWNEX OMEGA*
"""

        config_path.write_text(config, encoding="utf-8")

    def create_daily_note(self, date: Optional[datetime] = None) -> dict[str, Any]:
        """Crear nota diaria."""
        if date is None:
            date = datetime.now()

        date_str = date.strftime("%Y-%m-%d")
        filename = f"{date_str}.md"
        note_path = self.daily_notes_path / filename

        name = self.system.profile.preferred_name or self.system.profile.name
        goal = self.system.profile.primary_goal

        note_content = f"""---
created: {date_str}
tags: [daily, plan]
type: daily-note
---

# {date_str}

## 🧙 MERLIN Daily Plan for {name}

### 🎯 Objetivo del Día
{goal}

### ✅ Tareas Prioritarias
- [ ] Revisar objetivos del día
- [ ] Planificar tareas priorizadas
- [ ] Ejecutar con asistencia de MERLIN
- [ ] Registrar progreso

### 📊 Progreso
- [ ] Progreso 1
- [ ] Progreso 2

### 💡 Notas de MERLIN
{{{{daily_notes}}}}

### 🏆 Logros del Día
- Logro 1
- Logro 2

### 📝 Reflexión
{{{{reflection}}}}

---
*Generated by MERLIN - OWNEX OMEGA*
"""

        note_path.write_text(note_content, encoding="utf-8")

        return {
            "success": True,
            "note_path": str(note_path),
            "date": date_str,
        }

    def append_to_daily_note(self, content: str, date: Optional[datetime] = None) -> dict[str, Any]:
        """Agregar contenido a la nota diaria."""
        if date is None:
            date = datetime.now()

        date_str = date.strftime("%Y-%m-%d")
        filename = f"{date_str}.md"
        note_path = self.daily_notes_path / filename

        if not note_path.exists():
            self.create_daily_note(date)

        with open(note_path, "a", encoding="utf-8") as f:
            f.write(f"\n\n{content}\n")

        return {
            "success": True,
            "note_path": str(note_path),
            "date": date_str,
        }

    def create_merlin_note(self, title: str, content: str, tags: list[str] = None) -> dict[str, Any]:
        """Crear nota de MERLIN."""
        if tags is None:
            tags = ["merlin"]

        timestamp = datetime.now().strftime("%Y%m%d%H%M%S")
        filename = f"{timestamp} - {title}.md"
        note_path = self.merlin_notes_path / filename

        note_content = f"""---
created: {datetime.now().isoformat()}
tags: {tags}
type: merlin-note
---

# {title}

{content}

---
*Generated by MERLIN - OWNEX OMEGA*
"""

        note_path.write_text(note_content, encoding="utf-8")

        return {
            "success": True,
            "note_path": str(note_path),
            "title": title,
        }

    def get_daily_notes(self, limit: int = 7) -> list[dict[str, Any]]:
        """Obtener notas diarias recientes."""
        notes = []
        for note_path in sorted(self.daily_notes_path.glob("*.md"), reverse=True)[:limit]:
            with open(note_path, "r", encoding="utf-8") as f:
                content = f.read()
            notes.append({
                "path": str(note_path),
                "filename": note_path.name,
                "content": content,
            })
        return notes

    def get_merlin_notes(self, limit: int = 10) -> list[dict[str, Any]]:
        """Obtener notas de MERLIN recientes."""
        notes = []
        for note_path in sorted(self.merlin_notes_path.glob("*.md"), reverse=True)[:limit]:
            with open(note_path, "r", encoding="utf-8") as f:
                content = f.read()
            notes.append({
                "path": str(note_path),
                "filename": note_path.name,
                "content": content,
            })
        return notes


# Singleton instance
_obsidian_integration: Optional[ObsidianIntegration] = None


def get_obsidian_integration() -> ObsidianIntegration:
    """Obtener instancia singleton de integración Obsidian."""
    global _obsidian_integration
    if _obsidian_integration is None:
        _obsidian_integration = ObsidianIntegration()
    return _obsidian_integration


def reset_obsidian_integration() -> None:
    """Resetear instancia singleton."""
    global _obsidian_integration
    _obsidian_integration = None
