"""LLM Semantic HTTP Response Analyzer.

Replaces length-based diff with LLM-powered semantic comparison.
Understands whether two HTTP responses represent the same data,
different users' data, or fundamentally different states.

Optional — falls back to rule-based comparison when no LLM available.
"""

from __future__ import annotations

import json
import logging
from dataclasses import dataclass, field
from typing import Any

from cores.ai.provider import AIProvider, get_provider

logger = logging.getLogger("rastro.validation.llm_analyzer")

MAX_BODY_CHARS = 3000  # Truncate to avoid token overflow


@dataclass
class SemanticAnalysisResult:
    """Result from LLM-powered semantic analysis of two HTTP responses."""
    semantically_identical: bool  # Same data, different values? Or truly identical?
    same_resource: bool  # Both point to the same logical resource
    vulnerability_hints: list[str]  # What the LLM suspects
    explanation: str  # Human-readable reasoning
    confidence: float  # 0.0-1.0 how sure the LLM is
    raw_llm_response: str = ""


@dataclass
class PayloadSuggestion:
    """A single attack payload suggestion from the LLM."""
    attack_type: str  # sqli, xss, ssrf, path_traversal, idor, auth_bypass
    parameter: str  # Which parameter to target
    payload: str  # The actual payload string
    rationale: str  # Why this payload makes sense for this endpoint
    expected_outcome: str  # What to look for in the response
    risk_level: str  # low, medium, high, critical


@dataclass
class MutationPlan:
    """Complete mutation plan generated by LLM for an endpoint."""
    attack_vector: str  # Primary attack classification
    mutations: dict[str, str]  # parameter -> payload
    payloads: list[PayloadSuggestion] = field(default_factory=list)
    reasoning: str = ""
    auth_strategy: str = "same_user"  # same_user, different_user, anonymous


@dataclass
class LearningInsight:
    """An insight generated from analyzing human feedback patterns."""
    pattern: str  # What was learned (e.g. "SQLi on login endpoints often false-positive")
    confidence_adjustment: float  # How much to adjust confidence (-0.2 to +0.2)
    rule_weight_adjustment: dict[str, float]  # Per-rule weight changes
    recommendation: str  # Human-readable advice
    supporting_evidence: str  # Why the LLM thinks this
    source_count: int  # How many feedback events support this


class LLMInteractionMixin:
    """Shared LLM interaction logic for all three analyzers."""

    def __init__(self, provider: AIProvider | None = None):
        self._provider = provider or get_provider()
        self._usage_count = 0

    def _call_llm(self, system: str, user: str, max_tokens: int = 512) -> str | None:
        if not self._provider.is_available():
            return None
        self._usage_count += 1
        try:
            response = self._provider.chat([
                {"role": "system", "content": system},
                {"role": "user", "content": user},
            ], max_tokens=max_tokens)
            return response.strip() if response else None
        except Exception as e:
            logger.warning("LLM call failed: %s", e)
            return None

    def _json_from_llm(self, system: str, user: str) -> dict | None:
        response = self._call_llm(
            system + "\n\nRespond ONLY with valid JSON. No markdown, no explanation.",
            user,
            max_tokens=1024,
        )
        if not response:
            return None
        # Strip code fences if present
        if "```json" in response:
            response = response.split("```json")[1].split("```")[0].strip()
        elif "```" in response:
            response = response.split("```")[1].split("```")[0].strip()
        try:
            return json.loads(response)
        except json.JSONDecodeError:
            logger.warning("LLM returned invalid JSON: %s", response[:200])
            return None


class LLMResponseAnalyzer(LLMInteractionMixin):
    """Analyzes HTTP responses using LLM for semantic understanding.

    Detects:
    - Same data returned (identical records)
    - Same resource, different values (potential IDOR)
    - Error/access denied responses
    - Suspicious patterns the rules might miss
    """

    def semantic_compare(
        self,
        baseline_body: str,
        probe_body: str,
        endpoint_path: str,
        http_method: str,
        baseline_status: int,
        probe_status: int,
    ) -> SemanticAnalysisResult:
        """Compare two HTTP responses semantically using LLM.

        Falls back to a simple identical check when LLM unavailable.
        """
        # Fast path: identical bodies
        if baseline_body == probe_body:
            return SemanticAnalysisResult(
                semantically_identical=True,
                same_resource=True,
                vulnerability_hints=[],
                explanation="Responses are byte-identical.",
                confidence=1.0,
            )

        # Try LLM analysis
        system = """You are a security analysis AI. Compare two HTTP responses and determine:
1. Are they semantically the same data? (same user, same resource)
2. Do they represent the same resource with different values? (potential IDOR - different user's data)
3. Is one an error/denied while the other succeeds? (potential auth bypass)
4. Any suspicious patterns?

Respond with JSON: {
  "semantically_identical": bool,
  "same_resource": bool,
  "vulnerability_hints": [string],
  "explanation": "short reasoning",
  "confidence": 0.0-1.0
}"""

        user = (
            f"Endpoint: {http_method} {endpoint_path}\n"
            f"Baseline ({baseline_status}):\n```\n{baseline_body[:MAX_BODY_CHARS]}\n```\n\n"
            f"Probe ({probe_status}):\n```\n{probe_body[:MAX_BODY_CHARS]}\n```"
        )

        result = self._json_from_llm(system, user)
        if result:
            return SemanticAnalysisResult(
                semantically_identical=result.get("semantically_identical", False),
                same_resource=result.get("same_resource", True),
                vulnerability_hints=result.get("vulnerability_hints", []),
                explanation=result.get("explanation", "LLM analysis completed."),
                confidence=min(1.0, max(0.0, result.get("confidence", 0.5))),
                raw_llm_response=json.dumps(result),
            )

        # Fallback: length-based heuristic
        longer = max(len(baseline_body), len(probe_body))
        shorter = min(len(baseline_body), len(probe_body))
        ratio = 1.0 - (shorter / max(longer, 1))
        return SemanticAnalysisResult(
            semantically_identical=ratio < 0.05,
            same_resource=ratio < 0.30,
            vulnerability_hints=["body_length_differs"] if ratio > 0.05 else [],
            explanation=f"LLM unavailable. Fallback: length ratio={ratio:.2f}",
            confidence=max(0.0, 1.0 - ratio),
        )


class LLMRequestMutator(LLMInteractionMixin):
    """Generates contextually relevant attack payloads using LLM.

    Unlike the rule-based RequestMutator which only swaps IDs,
    this generates actual exploit payloads tailored to the endpoint.
    """

    ATTACK_TYPES = ["sqli", "xss", "ssrf", "path_traversal", "idor", "auth_bypass", "command_injection", "no_mutation"]

    def plan_mutations(
        self,
        url: str,
        method: str,
        params: dict[str, str],
        body: str | None,
        headers: dict[str, str],
        auth_label: str,
    ) -> MutationPlan:
        """Generate a complete mutation plan for this endpoint.

        Returns a no-mutation plan when LLM unavailable.
        """
        system = """You are a bug bounty hunter. Given an endpoint, plan the most promising attack mutations.

Return JSON: {
  "attack_vector": "sqli|xss|ssrf|path_traversal|idor|auth_bypass|command_injection",
  "mutations": {"param_name": "payload_value"},
  "payloads": [{"attack_type": "sqli", "parameter": "id", "payload": "' OR 1=1--", "rationale": "why", "expected_outcome": "what to look for", "risk_level": "high"}],
  "reasoning": "why this attack makes sense",
  "auth_strategy": "same_user|different_user|anonymous"
}

Prioritize real-world payloads. For SQLi use time-based or error-based.
For XSS use context-appropriate vectors. For SSRF use cloud metadata endpoints.
For path traversal use ../ sequences. For IDOR try adjacent IDs.
Only suggest mutations that make sense for this endpoint type."""

        param_summary = json.dumps(params, indent=2) if params else "none"
        user = (
            f"URL: {method} {url}\n"
            f"Params: {param_summary}\n"
            f"Body: {(body or 'none')[:500]}\n"
            f"Headers: {json.dumps(dict(headers))[:300]}\n"
            f"Auth: {auth_label}"
        )

        result = self._json_from_llm(system, user)
        if result:
            payloads = []
            for p in result.get("payloads", []):
                payloads.append(PayloadSuggestion(
                    attack_type=p.get("attack_type", "unknown"),
                    parameter=p.get("parameter", ""),
                    payload=p.get("payload", ""),
                    rationale=p.get("rationale", ""),
                    expected_outcome=p.get("expected_outcome", ""),
                    risk_level=p.get("risk_level", "medium"),
                ))
            return MutationPlan(
                attack_vector=result.get("attack_vector", "no_mutation"),
                mutations=result.get("mutations", {}),
                payloads=payloads,
                reasoning=result.get("reasoning", ""),
                auth_strategy=result.get("auth_strategy", "same_user"),
            )

        # Fallback: no mutations
        return MutationPlan(
            attack_vector="no_mutation",
            mutations={},
            reasoning="LLM unavailable. Using rule-based mutations.",
        )

    def suggest_endpoint_strategy(self, url: str, method: str) -> str:
        """Quick classification of what to test on this endpoint."""
        system = "Classify this endpoint for security testing. Respond with ONE word: sqli|xss|ssrf|idor|auth|generic"
        user = f"{method} {url}"
        result = self._call_llm(system, user)
        if result and result.lower() in self.ATTACK_TYPES:
            return result.lower()
        return "generic"


class FeedbackLearner(LLMInteractionMixin):
    """Analyzes human feedback patterns to improve validation accuracy.

    When a human confirms or rejects a pipeline verdict, this learner:
    1. Stores the feedback persistently
    2. Periodically analyzes patterns
    3. Adjusts confidence weights based on what it learns
    4. Generates human-readable insights
    """

    def __init__(self, provider: AIProvider | None = None):
        super().__init__(provider)
        self._pattern_cache: list[LearningInsight] = []

    def analyze_verdict_patterns(
        self,
        feedback_events: list[dict[str, Any]],
    ) -> list[LearningInsight]:
        """Analyze a batch of human feedback events for patterns.

        Each event should have: endpoint_path, attack_type, pipeline_verdict,
        human_verdict, confidence_score.
        """
        if not feedback_events or len(feedback_events) < 3:
            return []

        system = """You are a security ML engineer. Analyze these human-override events
where a human disagreed with the automated pipeline verdict.

For each pattern you find, return a JSON object describing what was learned.

Respond with a JSON array of: {
  "pattern": "description of what was learned",
  "confidence_adjustment": -0.2 to 0.2,
  "rule_weight_adjustment": {"rule_name": weight_change},
  "recommendation": "human-readable advice",
  "supporting_evidence": "why",
  "source_count": int
}

Focus on actionable patterns. Max 3 patterns."""

        events_summary = json.dumps(feedback_events[:20], indent=2, default=str)
        user = f"Analyze these {len(feedback_events)} human feedback events:\n\n{events_summary}"

        result = self._json_from_llm(system, user)
        insights = []
        if result and isinstance(result, list):
            for item in result:
                insights.append(LearningInsight(
                    pattern=item.get("pattern", "Unknown pattern"),
                    confidence_adjustment=max(-0.2, min(0.2, item.get("confidence_adjustment", 0.0))),
                    rule_weight_adjustment=item.get("rule_weight_adjustment", {}),
                    recommendation=item.get("recommendation", ""),
                    supporting_evidence=item.get("supporting_evidence", ""),
                    source_count=item.get("source_count", 1),
                ))
        elif result and isinstance(result, dict):
            insights.append(LearningInsight(
                pattern=result.get("pattern", "Learned pattern"),
                confidence_adjustment=max(-0.2, min(0.2, result.get("confidence_adjustment", 0.0))),
                rule_weight_adjustment=result.get("rule_weight_adjustment", {}),
                recommendation=result.get("recommendation", ""),
                supporting_evidence=result.get("supporting_evidence", ""),
                source_count=result.get("source_count", 1),
            ))

        self._pattern_cache = insights
        return insights

    def get_cached_insights(self) -> list[LearningInsight]:
        return self._pattern_cache

    def suggest_rule_tuning(self, insights: list[LearningInsight]) -> dict[str, Any]:
        """Convert learning insights into concrete rule tuning suggestions."""
        tuning: dict[str, Any] = {
            "confidence_weights": {},
            "rule_thresholds": {},
            "severity_overrides": [],
        }
        for insight in insights:
            if insight.confidence_adjustment != 0.0:
                tuning["confidence_weights"]["llm_adjustment"] = insight.confidence_adjustment
            for rule, adj in insight.rule_weight_adjustment.items():
                tuning["rule_thresholds"][rule] = adj
        return tuning
